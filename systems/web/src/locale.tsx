const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
const TRANSLATED_ATTRIBUTES = ["aria-label", "placeholder", "title"] as const;

function preserveWhitespace(source: string, translated: string): string {
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

export function translateText(source: string, locale: Locale): string {
  if (locale === "en" || !/[A-Za-z]/.test(source)) return source;
  const value = source.trim();
  const exact = KO_EXACT[value] ?? KO_ADDITIONAL[value] ?? KO_STATIC_REMAINDER[value] ?? SIMPLE_TOKENS[value];
  if (exact) return preserveWhitespace(source, exact);
  for (const [pattern, replacement] of KO_DYNAMIC) {
    const match = value.match(pattern);
    if (match) return preserveWhitespace(source, replacement(...match));
  }
  return source;
}

function localizeTextNode(node: Text, locale: Locale) {
  const current = node.data;
  let source = originalText.get(node);
  if (source === undefined || (current !== source && current !== translateText(source, "ko"))) {
    source = current;
    originalText.set(node, source);
  }
  const localized = translateText(source, locale);
  if (node.data !== localized) node.data = localized;
}

function localizeElement(element: Element, locale: Locale) {
  let saved = originalAttributes.get(element);
  if (!saved) {
    saved = new Map<string, string>();
    originalAttributes.set(element, saved);
  }
  for (const attribute of TRANSLATED_ATTRIBUTES) {
    const current = element.getAttribute(attribute);
    if (current === null) continue;
    const previous = saved.get(attribute);
    if (previous === undefined || (current !== previous && current !== translateText(previous, "ko"))) saved.set(attribute, current);
    const source = saved.get(attribute) ?? current;
    const localized = translateText(source, locale);
    if (localized !== current) element.setAttribute(attribute, localized);
  }
}

function localizeSubtree(root: Node, locale: Locale) {
  if (root.nodeType === Node.TEXT_NODE) {
    localizeTextNode(root as Text, locale);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  const element = root as Element;
  localizeElement(element, locale);
  const walker = document.createTreeWalker(element, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (node.nodeType === Node.TEXT_NODE) localizeTextNode(node as Text, locale);
    else localizeElement(node as Element, locale);
    node = walker.nextNode();
  }
}

function readInitialLocale(): Locale {
  try {
    return window.localStorage.getItem(STORAGE_KEY) === "ko" ? "ko" : "en";
  } catch {
    return "en";
  }
}

export function LocaleProvider({children}: {children: ReactNode}) {
  const [locale, setLocale] = useState<Locale>(readInitialLocale);
  const value = useMemo(() => ({locale, setLocale}), [locale]);

  useLayoutEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dataset.locale = locale;
    try { window.localStorage.setItem(STORAGE_KEY, locale); } catch { /* Browser storage can be unavailable in hardened contexts. */ }
    const root = document.getElementById("root") ?? document.body;
    localizeSubtree(root, locale);
    const observer = new MutationObserver((mutations) => {
      observer.disconnect();
      for (const mutation of mutations) {
        if (mutation.type === "characterData") localizeTextNode(mutation.target as Text, locale);
        if (mutation.type === "attributes") localizeElement(mutation.target as Element, locale);
        mutation.addedNodes.forEach((node) => localizeSubtree(node, locale));
      }
      observer.observe(root, {subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...TRANSLATED_ATTRIBUTES]});
    });
    observer.observe(root, {subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...TRANSLATED_ATTRIBUTES]});
    return () => observer.disconnect();
  }, [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}
